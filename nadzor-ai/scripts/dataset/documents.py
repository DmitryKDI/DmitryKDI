def ru_date(iso: str) -> str:
    y, m, d = iso.split("-")
    return f"{d}.{m}.{y}"


def stamp_for(obj: dict, code: str, section: str, stage: str, revision: str, date: str) -> dict:
    return {"code": code, "object": obj["name"][:90], "section": section, "stage": stage,
            "date": ru_date(date), "organization": obj["designer"],
            "chief_engineer": obj["chief_engineer"], "revision": revision, "sheet": "1"}


