"""Извлечение требований из прозы ПД — общий механизм, ЛЛМ вместо regex
(Приложение Г.36 CLAUDE.md).

`requirement_registry.py` разбирает прозу регулярками — но обе регулярки там
подобраны под ОДИН реальный документ, конкретный список противодымной
защиты («- из ..., пом. N, N (КОД);») и конкретную пару глагольных форм
(«предусмотрен(о/а)»/«предусматривается»). Пользователь прямо указал: те
примеры были иллюстрацией, не спецификацией, — будут другие типы
документов, с другими разделами, другой структурой прозы, другими
формулировками. Регулярка, подобранная под один документ, не обобщается на
следующий почти по определению: другой автор текста, другой раздел
(конструктив, электрика, слаботочка — не только ОВ), другой формат списка
или вообще без списка.

Здесь — тот же результат (`Requirement`: список помещений, код, если есть,
исходное предложение), но извлечённый ЛЛМ-вызовом по тексту страницы, а не
шаблоном регулярного выражения. Модель не должна предполагать какой-то
конкретный маркер списка или глагол — промпт прямо просит не опираться на
пример, а искать требование по смыслу: «этот текст обязывает что-то
сделать/предусмотреть для конкретного помещения/зоны, и/или у этого что-то
есть короткое обозначение».

`requirement_registry.py` (регулярки) не удалён — остаётся узким запасным
путём для прогона БЕЗ ключа ЛЛМ (RUN-NO-LLM.bat), с честной оговоркой в
собственном докстринге, что это не общий механизм. Этот модуль — путь по
умолчанию, когда ключ есть (RUN-VISION.bat)."""
from __future__ import annotations

from .llm import LlmConfig, call_llm_json
from .requirement_registry import Requirement
from .vision import UNTRUSTED_INPUT_RULE

REQUIREMENT_EXTRACTION_SYSTEM_PROMPT = f"""\
Ты помогаешь инспектору государственного строительного надзора составить
сводку требований из текста проектной документации (пояснительной записки
или другого текстового раздела ЛЮБОЙ дисциплины — не только инженерных
систем, это может быть конструктив, электрика, слаботочные системы, любой
раздел).

{UNTRUSTED_INPUT_RULE}

Тебе показан текст одной или нескольких страниц одного тома, каждая
страница отмечена меткой «--- Страница N ---» перед своим текстом.

Найди каждое ТРЕБОВАНИЕ — фрагмент текста, который обязывает что-то
предусмотреть, установить, выполнить или обеспечить ИМЕННО для конкретного
помещения, зоны, участка или оси, — и, если у требования (системы,
изделия, участка) есть короткое буквенно-числовое обозначение рядом
(код, марка, позиция) — код тоже.

ВАЖНО: не предполагай заранее, каким словом или значком помещение указано
в тексте («пом.», «каб.», «зал», просто число, название без номера) и
какой глагольной формой выражено требование («предусмотреть»,
«предусматривается», «необходимо», «должен быть», «выполнить», списком
через тире, обычным абзацем прозы, таблицей, пересказанной текстом, — форма
может быть любой). Читай по смыслу, а не по образцу конкретного документа.

Пропускай текст, который просто ОПИСЫВАЕТ существующее состояние или
местоположение объекта, а не формулирует обязывающее требование к
помещению (например, «установка находится в подвале» — не требование;
«для помещений N, N предусмотреть систему X» — требование).

Отвечай только JSON без пояснений вне JSON:
{{"requirements": [
  {{"rooms": ["как записано в тексте, каждое отдельным элементом"],
   "code": "короткое обозначение рядом с требованием, или null, если его нет",
   "requirement": "краткий пересказ сути требования, одно предложение",
   "sentence": "дословная цитата или близкий к дословному фрагмент исходного текста",
   "page": <int, номер страницы из метки>}}
]}}
Если требований на этих страницах нет — верни {{"requirements": []}}."""


def _chunk_text_facts(text_facts: list[dict], max_chars: int) -> list[list[dict]]:
    """Группирует страницы в пачки под потолок символов на один вызов —
    том пояснительной записки может быть сотни страниц, один вызов на всё
    сразу не влезет в контекст ни одной модели."""
    chunks: list[list[dict]] = []
    current: list[dict] = []
    current_len = 0
    for fact in text_facts:
        fact_len = len(fact["text"])
        if current and current_len + fact_len > max_chars:
            chunks.append(current)
            current, current_len = [], 0
        current.append(fact)
        current_len += fact_len
    if current:
        chunks.append(current)
    return chunks


def _render_chunk(chunk: list[dict]) -> str:
    return "\n\n".join(f"--- Страница {fact['page']} ---\n{fact['text']}" for fact in chunk)


def extract_requirements_llm(
    text_facts: list[dict],
    config: LlmConfig,
    max_chars_per_call: int = 6000,
    timeout: float = 120.0,
) -> list[Requirement]:
    """Требования из ЛЮБОЙ прозы ПД — постранично пачками под потолок
    символов, каждая пачка отдельным вызовом ЛЛМ. Сбой одной пачки (сеть,
    провайдер, неразбираемый ответ) не должен ронять извлечение по
    остальным — пропускается с пустым результатом для этой пачки, как и
    в остальных vision-путях этого пакета (Г.10)."""
    out: list[Requirement] = []
    for chunk in _chunk_text_facts(text_facts, max_chars_per_call):
        user_text = _render_chunk(chunk)
        try:
            result = call_llm_json(config, REQUIREMENT_EXTRACTION_SYSTEM_PROMPT, user_text, timeout=timeout)
        except Exception:  # noqa: BLE001 — сбой одной пачки не должен ронять извлечение по остальным
            continue
        if not result:
            continue
        for item in result.get("requirements", []):
            rooms = item.get("rooms") or []
            if not isinstance(rooms, list) or not rooms:
                continue
            page = item.get("page")
            if not isinstance(page, int):
                page = chunk[0]["page"]
            out.append(Requirement(
                rooms=[str(r) for r in rooms],
                page=page,
                sentence=str(item.get("sentence") or item.get("requirement") or ""),
                code=str(item["code"]) if item.get("code") else None,
            ))
    return out
