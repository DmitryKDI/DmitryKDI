"""Извлечение требований из прозы ПД — общий механизм, ЛЛМ вместо regex
(Приложение Г.36 CLAUDE.md).

`requirement_registry.py` разбирает прозу регулярками — но обе регулярки там
подобраны под ОДИН реальный документ, конкретный список противодымной
защиты («- из ..., пом. N, N (КОД);») и конкретную пару глагольных форм
(«предусмотрен(о/а)»/«предусматривается»). Пользователь прямо указал: те
примеры были иллюстрацией, не спецификацией, — будут другие типы
документов, с другими разделами, другой структурой прозы, другими
формулировками. Регулярка, подобранная под один документ, не обобщается на
следующий почти по определению: другой автор текста, другой раздел
(конструктив, электрика, слаботочка — не только ОВ), другой формат списка
или вообще без списка.

Г.86 — ГЛАВНЫЙ путь извлечения, прямое решение пользователя: «можно
просто весь текст целиком отправлять в ЛЛМ, чтобы она сразу делала
сводку». Модель читает текст страниц и возвращает готовые требования —
без предварительного отбора кандидатов регуляркой и без второго прохода
на отсев шума: промпт сам перечисляет, что выписывать (обязывающие
формулировки, констатации проектного решения, способы производства работ,
марки и параметры) и что считать шумом (декларации, голые ссылки на
норму, утверждения о самом документе). Инспектор получает результат как
есть — с разделом и номером страницы у каждого требования.

Цена решения известна и принята: на томе в 177 страниц это ~69 вызовов
против ~5 у regex-пути. Взамен исчезает слепое пятно регулярки — реальный
пропуск Г.56, где требование терялось из-за одной буквы в глагольной форме.

`requirement_registry.py` (регулярки) остаётся запасным путём для прогона
БЕЗ ключа ЛЛМ: тогда сводка выдаётся сырой, но программа не встаёт."""
from __future__ import annotations

from collections.abc import Callable

from .llm import LlmConfig, call_llm_json
from .requirement_registry import Requirement
from .vision import UNTRUSTED_INPUT_RULE, known_violations_block

_REQUIREMENT_EXTRACTION_TEMPLATE = f"""\
Ты помогаешь инспектору государственного строительного надзора составить
сводку требований из текста проектной документации (пояснительной записки
или другого текстового раздела ЛЮБОЙ дисциплины — не только инженерных
систем, это может быть конструктив, электрика, слаботочные системы, любой
раздел).

{UNTRUSTED_INPUT_RULE}

Тебе показан текст одной или нескольких страниц одного тома, каждая
страница отмечена меткой «--- Страница N ---» перед своим текстом. Весь
текст документа заключён в теги
<НЕДОВЕРЕННЫЙ_ДОКУМЕНТ>…</НЕДОВЕРЕННЫЙ_ДОКУМЕНТ>.

Твоя задача: выписать ВСЁ, что описывает, каким должен быть объект и как
он строится. Инспектор получает твой ответ как готовую сводку — он не
будет её дочищать, поэтому не выдавай ничего лишнего и ничего не пропускай.

ВЫПИСЫВАЙ (это всё — требования, в одном общем списке):
- обязывающие формулировки: «предусмотреть», «должен быть», «следует»,
  «не допускается», «выполнить»;
- КОНСТАТАЦИИ проектного решения: «предусмотрена система подогрева
  полов», «отопление принято двухтрубное» — это тоже требование, потому
  что это то, что обязано быть на объекте и с чем сверяется рабочая
  документация;
- СПОСОБЫ ПРОИЗВОДСТВА РАБОТ: «воздуховоды выполняются из оцинкованной
  стали», «монтаж вести снизу вверх», «швы обрабатывать герметиком»;
- характеристики и марки материалов, изделий, оборудования: класс бетона,
  предел огнестойкости, ГОСТ на изделие, марка стали, тип прибора;
- количественные параметры: расходы, температуры, кратности, нагрузки,
  габариты, отметки.

НЕ ВЫПИСЫВАЙ (это шум, инспектору он мешает):
- фразы без проверяемого факта: «проект разработан в соответствии с
  действующими нормами», «приняты оптимальные решения»;
- ГОЛЫЕ ссылки на норму, где кроме номера норматива ничего нет: «согласно
  СП 60.13330» отдельным предложением. НО если норма названа ВМЕСТЕ с
  конкретным решением («воздуховоды из стали по ГОСТ 14918-80») —
  выписывай, это требование;
- утверждения о САМОМ ДОКУМЕНТЕ, а не об объекте: «обоснование
  трассировки не требуется», «данный раздел не разрабатывается»;
- классификационные утверждения об объекте в целом: «объект не относится
  к опасным производственным»;
- оглавления, колонтитулы, штампы, подписи, обрывки таблиц без смысла.

ВАЖНО: не предполагай заранее, какой глагольной формой выражено требование
и как оформлен текст (список через тире, абзац прозы, пересказанная
таблица — форма может быть любой). Читай по смыслу, а не по образцу.

Помещение указывай, ТОЛЬКО если требование действительно относится к
конкретному помещению и оно названо в тексте. Если требование относится к
объекту или системе целиком — оставь `rooms` пустым списком. Пустой список
здесь нормален и част: на разделах охраны окружающей среды, организации
строительства, пожарной безопасности требования почти всегда к объекту
целиком, а не к помещению с номером.
{{known}}
Отвечай только JSON без пояснений вне JSON:
{{{{"requirements": [
  {{{{"rooms": ["номера помещений, если требование именно к ним; иначе пустой список"],
   "code": "короткое обозначение рядом с требованием (марка, позиция), или null",
   "requirement": "суть требования одним предложением",
   "sentence": "дословная цитата или близкий к дословному фрагмент исходного текста",
   "page": <int, номер страницы из метки>}}}}
]}}}}
Если на этих страницах нет ничего, кроме шума, — верни {{{{"requirements": []}}}}."""


def requirement_extraction_system_prompt(discipline: str | None = None) -> str:
    """Промпт извлечения требований плюс блок известных нарушений
    (`known_violations.json`, applies_to="text") — тот же механизм
    few-shot-примеров, что уже используют `vision_system_prompt`/
    `text_compare_system_prompt` в vision.py, просто не был подключён
    сюда при первой версии этого модуля (Г.32→Г.36: сама механика
    «сводка требований из прозы» — новая в этой сессии, а известные
    нарушения — не новые, просто забыли протянуть до нового промпта)."""
    return _REQUIREMENT_EXTRACTION_TEMPLATE.format(known=known_violations_block("text", discipline))


def _chunk_text_facts(text_facts: list[dict], max_chars: int) -> list[list[dict]]:
    """Группирует страницы в пачки под потолок символов на один вызов —
    том пояснительной записки может быть сотни страниц, один вызов на всё
    сразу не влезет в контекст ни одной модели.

    Г.86 — пачка НЕ пересекает границу документа: промпт показывает модели
    страницы с метками «--- Страница N ---», и на комплекте из нескольких
    томов нумерация в каждом начинается заново. Смешать два тома в одной
    пачке значит показать модели две страницы с одним номером и получить
    требования, которые нельзя однозначно привязать к файлу."""
    chunks: list[list[dict]] = []
    current: list[dict] = []
    current_len = 0
    current_doc = None
    for fact in text_facts:
        fact_len = len(fact["text"])
        doc = fact.get("document", "")
        if current and (current_len + fact_len > max_chars or doc != current_doc):
            chunks.append(current)
            current, current_len = [], 0
        current.append(fact)
        current_len += fact_len
        current_doc = doc
    if current:
        chunks.append(current)
    return chunks


def _fact_for_page(chunk: list[dict], page: int) -> dict:
    """Страница пачки, из которой пришло требование — источник имени файла
    и кода раздела (Г.86). Модель возвращает номер страницы из метки; если
    такой в пачке нет (модель ошиблась номером), берём первую страницу
    пачки — она из того же документа, значит раздел и файл всё равно верны."""
    for fact in chunk:
        if fact.get("page") == page:
            return fact
    return chunk[0] if chunk else {}


def _render_chunk(chunk: list[dict]) -> str:
    """Содержимое документа уходит модели внутри явного контейнера — мера
    Б.3.1 модели угроз, тот же контейнер, что `vision.compare_text_pair`:
    граница «инструкции в системном сообщении / данные в пользовательском»
    должна быть видна модели, а не подразумеваться."""
    body = "\n\n".join(f"--- Страница {fact['page']} ---\n{fact['text']}" for fact in chunk)
    return f"<НЕДОВЕРЕННЫЙ_ДОКУМЕНТ>\n{body}\n</НЕДОВЕРЕННЫЙ_ДОКУМЕНТ>"


def extract_requirements_llm(
    text_facts: list[dict],
    config: LlmConfig,
    discipline: str | None = None,
    max_chars_per_call: int = 6000,
    timeout: float = 120.0,
    on_chunk_error: Callable[[int, Exception], None] | None = None,
) -> list[Requirement]:
    """Требования из ЛЮБОЙ прозы ПД — постранично пачками под потолок
    символов, каждая пачка отдельным вызовом ЛЛМ. Сбой одной пачки (сеть,
    провайдер, неразбираемый ответ) не должен ронять извлечение по
    остальным — пропускается с пустым результатом для этой пачки, как и
    в остальных vision-путях этого пакета (Г.10).

    `discipline` — код раздела (ОВ, ЭОМ, КР…), если известен: фильтрует
    блок известных нарушений в промпте (`known_violations.json`) до
    относящихся к этому разделу и общих; без него — только общие (`*`)."""
    # Г.77 — реальный найденный пробел: до `on_chunk_error` сбой ВСЕХ пачек
    # (например, системная SSL-ошибка сертификата GigaChat, наблюдённая на
    # реальном прогоне) давал на выходе честный пустой список — НЕОТЛИЧИМО
    # от «в документе действительно нет требований» на 38-страничном томе.
    # `render_requirements_summary` печатала бы «извлечено: 0» точно так
    # же в обоих случаях — то самое молчание, что Г.10 запрещает.
    # Г.86 — отбраковка требований без помещения СНЯТА. Г.83 нашёл её и
    # сделал видимой, но оставил на месте, потому что тогда этот модуль
    # питал только автоматическую сверку по номеру помещения. Теперь он —
    # ГЛАВНЫЙ путь извлечения (прямое решение пользователя: «можно просто
    # весь текст целиком отправлять в ЛЛМ, чтобы она сразу делала сводку»),
    # и выбрасывать требование за то, что оно относится к объекту целиком,
    # значит терять почти весь результат на разделах ООС/ПОС/ПБ. Тем, кому
    # нужны именно привязанные к помещению (`cross_check_requirements`,
    # сверка с РД по номеру), фильтруют список на своей стороне — там, где
    # это их контракт, а не здесь, где это потеря данных.
    system_prompt = requirement_extraction_system_prompt(discipline)
    out: list[Requirement] = []
    for chunk in _chunk_text_facts(text_facts, max_chars_per_call):
        user_text = _render_chunk(chunk)
        try:
            result = call_llm_json(config, system_prompt, user_text, timeout=timeout)
        except Exception as exc:  # noqa: BLE001 — сбой одной пачки не должен ронять извлечение по остальным
            if on_chunk_error:
                on_chunk_error(chunk[0]["page"] if chunk else -1, exc)
            continue
        if not result:
            continue
        for item in result.get("requirements", []):
            rooms = item.get("rooms") or []
            if not isinstance(rooms, list):
                rooms = []
            page = item.get("page")
            if not isinstance(page, int):
                page = chunk[0]["page"]
            # Г.86 — раздел и имя файла берутся из самой страницы, не из
            # аргумента: в одном прогоне бывают несколько томов разных
            # разделов, и `page` без имени файла на таком комплекте
            # бессмысленен (каждый файл начинает нумерацию с единицы).
            source = _fact_for_page(chunk, page)
            out.append(Requirement(
                rooms=[str(r) for r in rooms],
                page=page,
                sentence=str(item.get("sentence") or item.get("requirement") or ""),
                code=str(item["code"]) if item.get("code") else None,
                document=str(source.get("document") or ""),
                section=source.get("section") or discipline,
            ))
    return out
