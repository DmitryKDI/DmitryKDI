"""Извлечение требований из прозы ПД — общий механизм, ЛЛМ вместо regex
(Приложение Г.36 CLAUDE.md).

`requirement_registry.py` разбирает прозу регулярками — но обе регулярки там
подобраны под ОДИН реальный документ, конкретный список противодымной
защиты («- из ..., пом. N, N (КОД);») и конкретную пару глагольных форм
(«предусмотрен(о/а)»/«предусматривается»). Пользователь прямо указал: те
примеры были иллюстрацией, не спецификацией, — будут другие типы
документов, с другими разделами, другой структурой прозы, другими
формулировками. Регулярка, подобранная под один документ, не обобщается на
следующий почти по определению: другой автор текста, другой раздел
(конструктив, электрика, слаботочка — не только ОВ), другой формат списка
или вообще без списка.

Г.86 — ГЛАВНЫЙ путь извлечения, прямое решение пользователя: «можно
просто весь текст целиком отправлять в ЛЛМ, чтобы она сразу делала
сводку». Модель читает текст страниц и возвращает готовые требования —
без предварительного отбора кандидатов регуляркой и без второго прохода
на отсев шума: промпт сам перечисляет, что выписывать (обязывающие
формулировки, констатации проектного решения, способы производства работ,
марки и параметры) и что считать шумом (декларации, голые ссылки на
норму, утверждения о самом документе). Инспектор получает результат как
есть — с разделом и номером страницы у каждого требования.

Цена решения известна и принята: на томе в 177 страниц это ~69 вызовов
против ~5 у regex-пути. Взамен исчезает слепое пятно регулярки — реальный
пропуск Г.56, где требование терялось из-за одной буквы в глагольной форме.

`requirement_registry.py` (регулярки) остаётся запасным путём для прогона
БЕЗ ключа ЛЛМ: тогда сводка выдаётся сырой, но программа не встаёт."""
