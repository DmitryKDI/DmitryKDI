"""Якорь в прозе (Приложение Г.19 CLAUDE.md) — ищет уже подтверждённый якорь
(номер помещения, обозначение системы) как отдельное слово в свободном
повествовательном тексте: пояснительной записке, «Ведомости изменений»,
разделе «Общие указания» — а не только в структурированной записи реестра
(rooms.py разбирает только табличную/подписную форму).

Голый токен-свип по всему корпусу не масштабируется на комплект с большим
каталогом/прайсом поставщика (сотни страниц с товарными артикулами дают
шум на короткие номера-якоря раньше, чем найдётся настоящее совпадение —
наблюдение с реального прогона). Поэтому здесь — не свип по всему тексту, а
двухшаговый фильтр: сначала абзацы со словами смены («заменен», «перенесен»,
«исключен», «добавлен», «ведомость изменений» и похожие), и только внутри
уже отфильтрованных абзацев — поиск якоря.
"""
from __future__ import annotations

import re

_CHANGE_WORD_RE = re.compile(
    r"замен[её]н|перенес[её]н|перемещ[её]н|исключ[её]н|добавлен|"
    r"ведомост[а-я]*\s+изменени|измен[её]н[а-я]*\s+схем", re.I)

# Абзацы в извлечённом из PDF тексте почти никогда не разделены пустой
# строкой — граница чаще держится на конце предложения перед заглавной
# буквой следующего или на явном переводе строки. Оба варианта — рабочий
# компромисс, не точный парсер: цель — не потерять словосочетание со
# словом смены, а не построить безупречную сегментацию текста.
_PARAGRAPH_SPLIT_RE = re.compile(r"\n\s*\n|(?<=[.!?])\s+(?=[А-ЯЁ\d])")


def _split_paragraphs(text: str) -> list[str]:
    parts = [p.strip() for p in _PARAGRAPH_SPLIT_RE.split(text)]
    return [p for p in parts if p]


def _anchor_pattern(anchor: str) -> re.Pattern:
    # Якорь может содержать точку («006.1») — экранируем её буквально, но
    # оставляем границы слова с обеих сторон, чтобы «12» не совпало внутри
    # «112» или «12.3».
    return re.compile(rf"(?<!\d){re.escape(anchor)}(?!\d)(?!\.\d)")


def find_anchor_in_prose(text_facts: list[dict], anchors: set[str]) -> list[dict]:
    """Ищет каждый якорь из `anchors` внутри абзацев со словами смены.

    `text_facts` — уже отфильтрованные страницы документа (см. documents.py:
    material.py исключает непроектный материал раньше, чем текст попадает
    сюда). Возвращает [{page, anchor, paragraph}] — по записи на каждое
    найденное совпадение якоря внутри подходящего абзаца."""
    if not anchors:
        return []
    patterns = {a: _anchor_pattern(a) for a in anchors}
    hits: list[dict] = []
    for fact in text_facts:
        page = fact["page"]
        for paragraph in _split_paragraphs(fact["text"]):
            if not _CHANGE_WORD_RE.search(paragraph):
                continue
            for anchor, pattern in patterns.items():
                if pattern.search(paragraph):
                    hits.append({"page": page, "anchor": anchor, "paragraph": paragraph})
    return hits
