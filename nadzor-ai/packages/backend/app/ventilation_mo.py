"""Сверка «система/ветка → помещение» ПД↔РД по таблице воздухообменов
(Приложение Г.58/Г.59).

Общий механизм, не частный случай одного нарушения: ЛЮБАЯ таблица ПД,
которая назначает помещению конкретную систему вентиляции и (если есть)
ветку местного отсоса, должна физически подтверждаться на плане РД у ТОГО
ЖЕ помещения — не у соседнего, не под другим именем системы. Конкретный
наблюдённый случай (нарушение №3 разобранного объекта, местные отсосы —
вытяжные шкафы лабораторий) — первый и пока единственный пример этого
общего класса, а не то, ради чего механизм писан узко.

Оба листа читаются ТОЛЬКО зрением — не в порядке выбора, а по факту:
- текстовый слой таблицы воздухообменов пуст (`page.get_text()` отдаёт
  только штамп) — сама таблица в кривых/растре;
- подписи веток на плане РД («В2.7» и т.п.) тоже в кривых — проверено
  прямым `page.search_for()` на реальном листе, ни одна не нашлась.

Тот же вывод, что уже был сделан для routing_graph.py (Г.44): для этого
комплекта векторного текста нет, деterministic-путь недоступен, нужен
именно ИИ. `is_mo_table_page` — единственная деterministic часть модуля
(заголовок листа читается текстом, это подтверждено).

Обобщение заголовка (Г.59, по прямому требованию пользователя — механизм
должен переноситься на другие документы, не только на этот прогон):
искать не дословную фразу «Таблица воздухообменов помещений» одного
конкретного автора, а корень «воздухообмен» — это термин СП 60.13330
«Отопление, вентиляция и кондиционирование воздуха», обязательный для
такого расчёта в любом проекте этого раздела, а не соглашение одного
разработчика. Другие авторы называют лист иначе («Ведомость
воздухообменов», «Расчёт воздухообмена помещений», «Таблица
воздухообмена») — все формы содержат этот корень, поэтому сужение до
дословной фразы было бы overfitting под один комплект (тот же урок, что
Г.42 уже применял к другим модулям). Статус переноса, как и положено при
n=1 (Г.21): не проверено на втором реальном комплекте, только на
терминологии стандарта — не выдаётся за большее."""
