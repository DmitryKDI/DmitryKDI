# Корень термина СП 60.13330 («воздухообменов», «воздухообмена», ...) и
# порог длины страницы (ниже) записаны в реестре `table_registry.py`
# (kind="ventilation_balance") — здесь только сама граница (используется
# явно в вызове `classify_table_page` ниже), сам regex туда не дублируется.
#
# Одного упоминания термина мало: он же встречается в содержании тома
# («Таблица воздухообменов помещений (начало)» — заголовок листа,
# перечисленный в списке чертежей) и в обычной прозе ПЗ («Воздухообмен в
# столовой... рассчитан на...») — оба реально найдены на разобранном ПД
# при первой же проверке обобщённого корня (Г.59), не гипотеза. Отличает
# настоящий лист таблицы устойчивый признак того же класса, что и Г.8
# («бедный текстовый слой» как видимое состояние, не помеха): у листа,
# где сама таблица в кривых, извлекается только штамп — весь текст
# страницы короткий (реально ~460 символов на разобранном комплекте),
# тогда как страница содержания или прозы ПЗ — на порядок длиннее (в
# разобранном ПД: 1483-2488 символов). Порог взят с запасом.
_TABLE_PAGE_MAX_TEXT_LEN = 800


def is_mo_table_page(text_facts: list[dict], page_no: int) -> bool:
    """Деterministic-проверка: заголовок листа читается текстом, даже
    когда сама таблица — нет (штамп и заголовок остаются векторным
    текстом чаще, чем ячейки таблицы). Ищет корень стандартного термина
    (Г.59), не фразу одного конкретного документа — «Таблица
    воздухообменов помещений» этого комплекта такая же находка, как
    «Ведомость воздухообмена» или «Расчёт воздухообменов» были бы в
    другом. Требует ТАКЖЕ короткий текст всей страницы — иначе матчатся
    страница содержания тома и обычная проза ПЗ, которые термин тоже
    упоминают, но таблицей не являются.

    Г.66 — этот регекс/порог теперь также записаны как одна из строк
    общего реестра `table_registry.py` (kind="ventilation_balance") —
    функция ниже делегирует туда для единообразия (то же самое условие,
    та же граница), а не переизобретает его локально. Поведение не
    поменялось: тот же regex, тот же порог 800 символов, те же тесты
    продолжают проходить без изменений."""
    kind = classify_table_page(text_facts, page_no, max_text_len=_TABLE_PAGE_MAX_TEXT_LEN)
    return kind is not None and kind.kind == "ventilation_balance"


_MO_TABLE_SYSTEM_PROMPT = f"""\
Ты помогаешь инспектору государственного строительного надзора сверить
проектную документацию с рабочей. Тебе показан лист «Таблица
воздухообменов помещений» из проектной документации (ПД) — таблица со
столбцами: номер помещения, наименование, система приточной вентиляции,
система вытяжной вентиляции, и (если есть) наименование системы местных
отсосов (М.О. — вытяжных шкафов лабораторий) со столбцом «Вытяжка от
М.О.» и обозначением веток (например «В2.7, В2.8, В2.9»).

{UNTRUSTED_INPUT_RULE}

Прочитай ВСЕ строки таблицы на листе — каждый номер помещения в первом
столбце, даже если у него нет местных отсосов. Для КАЖДОГО номера
помещения на листе добавь его в список "rooms_seen" (просто список
номеров, без прочих полей). Отдельно, для помещений, где столбец местных
отсосов (М.О.) не пустой (не прочерк «-»), добавь подробную запись в
список "rooms" — остальные подробностей не требуют.

Отвечай только JSON без пояснений вне JSON:
{{"rooms_seen": ["100", "101", "102"],
 "rooms": [{{"room": "140", "name": "физического эксперимента",
 "supply_system": "П6", "exhaust_system": "ВЕ",
 "mo_branches": ["В2.7", "В2.8", "В2.9"], "mo_note": "текст из столбца, как есть"}}],
 "injection_suspected": false}}"""


def extract_mo_table_page(
    pdf_path: str, page_no: int, config: LlmConfig, timeout: float = 120.0,
) -> dict:
    """Одна страница «Таблицы воздухообменов» → `{"rooms": [...], "rooms_seen": [...]}`.

    Г.60 — реальный наблюдённый пропуск: помещение, которого в таблице
    просто НЕТ СТРОКОЙ (в разобранном ПД — целая группа «Робо-класс»,
    номера 307-316, таблица перескакивает с 306 сразу на 317), выглядело
    бы для вызывающего кода неотличимо от помещения, у которого строка
    ЕСТЬ, но столбец местных отсосов пуст — оба давали бы «отсутствует в
    `rooms`». Разница огромная: одно — «этому помещению просто не нужны
    местные отсосы» (тишина законна), другое — «эта таблица вообще не
    источник данных по этому помещению, нужен другой» (тишина здесь —
    как раз то, что Г.10 запрещает). `rooms_seen` — все номера, что
    физически есть на листе, независимо от местных отсосов; вызывающий
    код (`find_uncovered_rooms`) сверяет запрошенные номера с этим
    списком по ВСЕМ страницам таблицы, не с одним `rooms`."""
    img = render_page_to_data_url(pdf_path, page_no)
    try:
        result = call_llm_json(
            config, _MO_TABLE_SYSTEM_PROMPT,
            "Прочитай таблицу и верни все помещения со столбцом местных отсосов.",
            images=[img], timeout=timeout,
        )
    except Exception as exc:  # noqa: BLE001 — сбой одной страницы не должен ронять весь прогон
        # (реальный найденный баг: невалидный api_key/сетевой сбой здесь
        # раньше пробрасывался наружу необработанным и обрушивал ВЕСЬ
        # --kind all/run_triangulated, хотя все соседние ЛЛМ-вызовы в этом
        # же прогоне (verdict_synthesis.py, requirement_text_verify.py,
        # vision_page_compare.py) уже ловят исключение на этом же месте —
        # см. их try/except вокруг call_llm_json. Видимое состояние (Г.10),
        # не тихий пропуск и не падение всего прогона.
        return {"rooms": [], "rooms_seen": [], "error": repr(exc)}
    if not result:
        return {"rooms": [], "rooms_seen": [], "error": None}
    rooms = result.get("rooms") if isinstance(result.get("rooms"), list) else []
    rooms_seen = result.get("rooms_seen") if isinstance(result.get("rooms_seen"), list) else []
    return {"rooms": rooms, "rooms_seen": rooms_seen, "error": None}


def find_uncovered_rooms(requested_rooms: list[str], rooms_seen: set[str]) -> list[str]:
    """Запрошенные номера помещений, которых нет НИ В ОДНОЙ странице
    таблицы воздухообменов вообще — не «нет местных отсосов», а «эта
    таблица не источник данных по этому помещению». Видимое состояние
    (Г.10), не молчаливое исключение из отчёта."""
    return [r for r in requested_rooms if r not in rooms_seen]


_BRANCH_LOCATIONS_SYSTEM_PROMPT = f"""\
Ты помогаешь инспектору государственного строительного надзора сверить
проектную документацию с рабочей. Тебе показан лист плана вентиляции
(рабочая документация, РД) с воздуховодами. На листе есть подписанные
номера помещений (в кружках или рядом с контуром) и подписи веток
местных отсосов вида «В2.7», «В2.8» и т.п. (вытяжка от вытяжных шкафов),
а также обозначение подключённой приточной/вытяжной системы (например
«П2/ВЕ»).

{UNTRUSTED_INPUT_RULE}

Для КАЖДОЙ подписи ветки местного отсоса («В...») на листе определи, у
какого помещения (по номеру) она физически нарисована — то есть рядом с
каким кружком номера помещения проходит труба этой ветки. Если труба
проходит через несколько помещений транзитом — указывай то, где
установлен сам вытяжной шкаф (начало ветки), не транзитный коридор.

Отвечай только JSON без пояснений вне JSON:
{{"branches": [{{"branch": "В2.7", "nearest_room": "140", "system": "П2/ВЕ"}}],
 "injection_suspected": false}}"""


def extract_branch_locations(
    pdf_path: str, page_no: int, config: LlmConfig, timeout: float = 120.0,
) -> list[dict]:
    """Один лист плана РД → список веток местных отсосов с ближайшим
    помещением и обозначением системы у этого помещения."""
    img = render_page_to_data_url(pdf_path, page_no)
    try:
        result = call_llm_json(
            config, _BRANCH_LOCATIONS_SYSTEM_PROMPT,
            "Определи для каждой ветки местного отсоса ближайшее помещение.",
            images=[img], timeout=timeout,
        )
    except Exception:  # noqa: BLE001 — тот же принцип, что extract_mo_table_page выше:
        # сбой одной страницы РД не должен ронять весь прогон. Деградация
        # ("на этом листе веток не нашли") уже была легитимным исходом для
        # неразбираемого ответа — обрабатываем сбой вызова так же.
        return []
    if not result or not isinstance(result.get("branches"), list):
        return []
    return result["branches"]


@dataclass
class MoFinding:
    room: str
    finding_type: str  # "system_mismatch" | "branch_missing" | "branch_relocated"
    detail: str
    severity: str = "существенно"


def cross_check_mo_branches(pd_rooms: list[dict], rd_branches: list[dict]) -> list[MoFinding]:
    """Сравнивает таблицу ПД (`extract_mo_table_page`, по помещениям) с
    прочитанными ветками РД (`extract_branch_locations`, по веткам) —
    разная единица группировки с двух сторон, поэтому сначала РД
    переворачивается в {ветка: (помещение, система)}.

    Три типа находок:
    - system_mismatch — система у помещения на РД не совпадает с ПД
      (пример реального прогона: ПД «П6», РД «П2»);
    - branch_missing — ветка, назначенная помещению в ПД, на РД не
      найдена ни у одного помещения вообще;
    - branch_relocated — ветка найдена на РД, но у ДРУГОГО помещения, не
      у того, что в ПД (пример реального прогона: В2.10 — в ПД у 147,
      на РД нарисована у 140)."""
    rd_by_branch = {b["branch"]: b for b in rd_branches if b.get("branch")}
    findings: list[MoFinding] = []
    for pd_room in pd_rooms:
        room = pd_room.get("room")
        if not room:
            continue
        pd_supply = pd_room.get("supply_system", "")
        branches = pd_room.get("mo_branches") or []
        systems_seen: set[str] = set()
        for branch in branches:
            rd_entry = rd_by_branch.get(branch)
            if rd_entry is None:
                findings.append(MoFinding(
                    room=room, finding_type="branch_missing",
                    detail=f"ветка {branch} (ПД, помещение {room}) не найдена ни у одного "
                           f"помещения на плане РД",
                ))
                continue
            rd_room = rd_entry.get("nearest_room")
            if rd_room and rd_room != room:
                findings.append(MoFinding(
                    room=room, finding_type="branch_relocated",
                    detail=f"ветка {branch} в ПД относится к помещению {room}, "
                           f"на РД нарисована у помещения {rd_room}",
                ))
            if rd_entry.get("system"):
                systems_seen.add(rd_entry["system"])
        for rd_system in systems_seen:
            rd_supply = rd_system.split("/")[0].strip() if "/" in rd_system else rd_system
            if pd_supply and rd_supply and pd_supply != rd_supply:
                findings.append(MoFinding(
                    room=room, finding_type="system_mismatch",
                    detail=f"помещение {room}: система в ПД «{pd_supply}», на РД «{rd_supply}»",
                ))
    return findings


def render_mo_cross_check_report(findings: list[MoFinding]) -> str:
    lines = [f"=== Сверка местных отсосов ПД↔РД по таблице воздухообменов (Г.58) — находок: {len(findings)} ==="]
    for f in findings:
        lines.append(f"  [{f.severity}] пом. {f.room} ({f.finding_type}): {f.detail}")
    return "\n".join(lines)
