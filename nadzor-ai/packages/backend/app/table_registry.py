"""Общий реестр известных типов таблиц проектной/рабочей документации
(Приложение Г.66) — заготовка по прямому запросу пользователя.

Прямой повод: `ventilation_mo.is_mo_table_page` (Г.58/Г.59) находит ОДИН
конкретный тип таблицы («Таблица воздухообменов», термин раздела ОВ) по
regex на корень одного слова — пользователь спросил в лоб, обобщён ли
механизм классификации таблиц вообще, или он способен узнавать только
вентиляционную таблицу. Ответ был честным: только вентиляционную. Этот
модуль — прямое обобщение: не «один regex под одну таблицу», а РЕЕСТР
известных типов таблиц разных разделов, каждый со своим normative-термином,
и общая функция `classify_table_page`, которая проверяет их все разом и
возвращает, КАКОЙ тип таблицы это (если это вообще известный тип).

ВАЖНО — статус честности (Г.11/Г.21), не подать заготовку за проверенный
факт:
  - `ventilation_balance` (воздухообмены, ОВ) — единственная запись со
    статусом n=1: подтверждена на реальном комплекте (Г.58/Г.59,
    ventilation_mo.py). У неё же есть РАБОТАЮЩАЯ сверка ПД↔РД
    (`cross_check_mo_branches`).
  - Все остальные записи — n=0, заготовка: термин обоснован нормативным
    источником (ГОСТ/СП, указан в `description_ru`/`status` каждой
    записи — тот же класс обоснования, что Г.36/Г.47/Г.59 уже применяли к
    другим модулям), но НИ РАЗУ не проверен на реальном листе этого или
    другого комплекта. У них также НЕТ функции извлечения данных из
    таблицы и сверки ПД↔РД — этот модуль умеет только УЗНАТЬ страницу как
    «похоже, таблица такого-то типа», не читать её содержимое. Реальный
    экстрактор для каждого нового типа — отдельная работа, требующая
    реального листа этого раздела (тот же принцип, что уже применялся к
    ventilation_mo.py, composition_registry.py и т.д. — код пишется на
    реальном примере, не наперёд).

Используется тот же признак «короткий текст страницы», что Г.59/Г.8 уже
установили для вентиляционной таблицы: настоящая таблица со значениями в
кривых (CAD-экспорт) даёт на странице только штамп, короткий текст,
тогда как страница содержания тома или обычная проза, где термин просто
упомянут, — на порядок длиннее. Перенос этого признака на другие разделы
пока не проверен отдельно (n=0 наравне с самими терминами) — но сам
принцип (штамп короче содержания) не специфичен для ОВ, поэтому взят как
разумный дефолт, а не изобретён заново."""
