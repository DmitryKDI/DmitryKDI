def classify_table_page(
    text_facts: list[dict], page_no: int, max_text_len: int = DEFAULT_MAX_TABLE_PAGE_TEXT_LEN,
) -> Optional[TableKind]:
    """Проверяет ВСЕ известные типы таблиц реестра разом. Возвращает первую
    совпавшую запись `TableKind` или `None`, если страница не похожа ни на
    одну известную таблицу (что законно — большинство страниц любого
    комплекта не таблицы вообще, Г.10)."""
    page_text = "".join(f["text"] for f in text_facts if f["page"] == page_no)
    if len(page_text) > max_text_len:
        return None
    for kind in _REGISTRY:
        if kind.title_re.search(page_text):
            return kind
    return None


def all_known_kinds() -> list[TableKind]:
    """Весь реестр — для показа инспектору/разработчику, какие типы таблиц
    система вообще умеет узнавать (и с честной пометкой n=0/n=1 у каждой)."""
    return list(_REGISTRY)
