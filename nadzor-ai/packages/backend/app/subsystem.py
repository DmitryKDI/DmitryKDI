"""Грубое различение подсистем «вентиляция» и «отопление» внутри одного
раздела ОВ по ключевым словам.

Код раздела по ГОСТ Р 21.1101 не различает их («ОВ2.1» и «ОВ1» — один и тот
же раздел, см. classification.py), но на реальных документах подсистемы
подшиваются в разные тома (пример из практики: РД-ОВ1 — вентиляция,
РД-ОВ2.1 — отопление), а в подвальных технических помещениях оба тома
описывают одни и те же номера помещений (венткамера и тепловой узел часто в
одном техническом подполье) — из-за этого чистое совпадение номеров
помещений (rooms.py) само по себе не отличает их. Здесь — мягкая подсказка
для matching.py, не гейтинг: при разногласии совпадение просто становится
менее вероятным, эвристика по словам не претендует на надёжность гейта.

Явление «два тома одной подсистемы с совпадающими номерами помещений»
специфично для раздела ОВ — matching.py вызывает эту функцию только для
файлов с `discipline_code == "ОВ"`, на любом другом разделе (КР, ЭОМ, ВК...)
эти же слова могут встретиться случайно и дать ложный сигнал там, где
самого явления не существует."""
from __future__ import annotations

from typing import Optional

_VENT_WORDS = ("вентиляц", "воздуховод", "приточ", "вытяжн", "аспираци",
               "венткамер", "форкамер", "калорифер", "вентилятор", "воздухозабор")
_HEAT_WORDS = ("отопление", "отопительн", "радиатор", "тёплый пол", "теплый пол",
               "полотенцесуш", "элеватор", "теплоснабж")
_MARGIN = 2  # разница меньше этого — сигнала недостаточно, чтобы доверять эвристике


def subsystem_lean(text: str) -> Optional[str]:
    """'вент' | 'тепл' | None."""
    low = text.lower()
    vent = sum(low.count(w) for w in _VENT_WORDS)
    heat = sum(low.count(w) for w in _HEAT_WORDS)
    if vent - heat >= _MARGIN:
        return "вент"
    if heat - vent >= _MARGIN:
        return "тепл"
    return None
