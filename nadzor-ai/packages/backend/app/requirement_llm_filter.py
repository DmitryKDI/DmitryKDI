_FILTER_SYSTEM_PROMPT = f"""\
Ты помогаешь инспектору государственного строительного надзора очистить
черновой список кандидатов в требования, извлечённый простым текстовым
поиском (regex) из прозы проектной документации ЛЮБОГО раздела (не только
инженерных систем — это может быть конструктив, электрика, слаботочка,
архитектура, любой раздел).

Черновой поиск сознательно широкий и содержит шум: общие декларативные
фразы без содержания, голые ссылки на нормативный документ без другого
содержания, обрывки таблиц, случайно попавшие фрагменты. Тебе показан
пронумерованный список кандидатов — по каждому номеру реши: это
настоящее ТРЕБОВАНИЕ (несёт конкретный, проверяемый технический факт про
помещение, зону, систему или объект — что для него предусмотрено,
установлено, выполнено, обеспечено, каким способом или из какого
материала исполнено), или ШУМ.

ВАЖНО — не суди строго по наличию модального глагола долженствования
(«должен», «обязан», «необходимо»). Предложение, которое КОНСТАТИРУЕТ
факт проекта («предусмотрена система X», «применяется материал Y»,
«устанавливается оборудование N»), или ОПИСЫВАЕТ конкретный способ
исполнения работ («выполняется из стали», «прокладывается по такой-то
трассе») — это ТОЖЕ полноценное требование для этой задачи, даже если по
форме это не приказ, а описание проектного решения: инспектор сравнивает
именно такие факты с тем, что реально сделано в рабочей документации,
независимо от грамматического наклонения.

НО этот критерий («описывает способ исполнения») относится ТОЛЬКО к
предложениям, где называется конкретное ПОЛОЖИТЕЛЬНОЕ техническое решение
для конкретной части объекта (материал, класс, марка, размер, трасса,
способ монтажа) — не к любому предложению, где просто УПОМЯНУТА система
или процесс. Само по себе наличие в тексте слова «система», «материал»,
«трасса» и т.п. НЕ делает предложение требованием — важно, утверждается
ли реальный факт ПРО ОБЪЕКТ, с которым можно построчно свериться в
рабочей документации.

СТРОГО ШУМОМ считай, даже если предложение упоминает систему, материал
или процесс работ:

1. Общие декларативные фразы без факта («проект разработан в соответствии
   с требованиями...», «раздел выполнен на основании...»).
2. Голая ссылка на нормативный документ без другого содержания.
3. Обрывок таблицы или служебного текста, случайный фрагмент.
4. Чисто локация БЕЗ факта для сравнения («установка находится в
   подвале» — это где, а не что именно сделано).
5. МЕТА-УТВЕРЖДЕНИЯ ОБ ОБЪЁМЕ САМОГО РАЗДЕЛА ДОКУМЕНТА, не о физическом
   объекте: предложения о том, что какое-то обоснование, расчёт, перечень
   мероприятий или пояснение В ЭТОМ РАЗДЕЛЕ НЕ ТРЕБУЕТСЯ / НЕ ПРИВОДИТСЯ /
   ОТСУТСТВУЕТ ВВИДУ НЕПРИМЕНИМОСТИ (характерные обороты: «нет необходимости»,
   «не требуется», «не предусматривается ввиду того что...», «раздел не
   содержит», «необходимости нет»). Это утверждение о ТОМ, ЧТО НЕ НУЖНО
   ВКЛЮЧАТЬ В ДОКУМЕНТ, а не
   факт о физическом объекте — сравнивать в рабочей документации попросту
   нечего, там не будет ни подтверждения, ни опровержения отсутствующего
   по этой же причине раздела. Условный пример структуры (формулировку не
   копировать буквально — это иллюстрация принципа, не образец с реального
   объекта): «Обоснование резервирования инженерных систем: для объектов
   такого класса не требуется» — ШУМ, хотя предложение и упоминает
   «резервирование инженерных систем».
6. Утверждения о том, что объект/система НЕ ОТНОСЯТСЯ или НЕ ПРЕДНАЗНАЧЕНЫ
   для какой-то категории, режима или условий эксплуатации («не относится
   к производственным зданиям», «не предназначен для работы в особых
   условиях», «не является объектом повышенной опасности») — это
   классификационное суждение о категории объекта в целом, а не
   утверждение о конкретном техническом решении, которое можно построчно
   сверить с рабочей документацией.

{UNTRUSTED_INPUT_RULE}

Отвечай только JSON без пояснений вне JSON:
{{"verdicts": [
  {{"index": <int, номер кандидата из списка>,
   "is_requirement": true | false,
   "reasoning": "1 короткая фраза почему"}}
]}}
Ответь по КАЖДОМУ номеру из списка, ни один не пропускай."""


@dataclass(frozen=True)
class RequirementVerdict:
    """Решение ЛЛМ по одному кандидату формы 3."""
    requirement: Requirement
    is_requirement: bool
    reasoning: str


_NO_VERDICT_REASON = ("ЛЛМ не дала вердикт по этому пункту (сбой вызова или "
                      "пропуск в ответе) — оставлено как требование, не выброшено молча")


def _chunk_requirements(requirements: list[Requirement], batch_size: int) -> list[list[Requirement]]:
    return [requirements[i:i + batch_size] for i in range(0, len(requirements), batch_size)]


def _parse_verdict_bool(value, default: bool) -> bool:
    """`item.get("is_requirement", True)` было бы честной логикой ТОЛЬКО
    если бы значение всегда приходило JSON-литералом (`true`/`false`).
    GigaChat здесь не даёт строгой JSON-схемы (Г.39 — отклоняет
    `response_format: json_object`, JSON запрашивается текстом промпта) —
    реальный наблюдённый случай (Г.74): модель может вернуть булево как
    СТРОКУ `"false"`, и `bool("false")` в Python — `True` (любая непустая
    строка истинна), то есть каждый настоящий отрицательный вердикт молча
    превращался бы в положительный уже на этапе разбора ответа, ДО того,
    как решение модели вообще увидит `render_general_requirements_summary_llm_filtered`
    — снаружи это неотличимо от «модель просто ничего не отсеивает»."""
    if isinstance(value, bool):
        return value
    if isinstance(value, str):
        normalized = value.strip().lower()
        if normalized in ("true", "1", "yes", "да"):
            return True
        if normalized in ("false", "0", "no", "нет"):
            return False
    if isinstance(value, (int, float)):
        return bool(value)
    return default


def _render_batch(batch: list[Requirement]) -> str:
    body = "\n".join(f"{i}. «{r.sentence}»" for i, r in enumerate(batch, 1))
    return f"<НЕДОВЕРЕННЫЙ_ДОКУМЕНТ>\nСписок кандидатов:\n{body}\n</НЕДОВЕРЕННЫЙ_ДОКУМЕНТ>"


def classify_general_requirements(
    requirements: list[Requirement],
    config: LlmConfig,
    batch_size: int = 20,
    timeout: float = 90.0,
    on_batch_error: Optional[Callable[[list[Requirement], Exception], None]] = None,
) -> list[RequirementVerdict]:
    """Классифицирует ВЕСЬ список кандидатов формы 3 пачками по
    `batch_size`. Порядок сохраняется (индекс в результате соответствует
    порядку во входном списке, не порядку ответа модели).

    Г.77 — реальный найденный пробел: сбой ВЕЙ пачки (например, системная
    SSL-ошибка сертификата GigaChat, реально наблюдённая на живом прогоне)
    давал каждому кандидату честный, но НЕВИДИМЫЙ фолбэк
    (`is_requirement=True`, `reasoning="ЛЛМ не дала вердикт..."`) —
    невидимый потому, что `render_general_requirements_summary_llm_filtered`
    печатает `reasoning` ТОЛЬКО для отсеянных пунктов, а этот фолбэк всегда
    `is_requirement=True`, то есть кандидат уходит в «оставленные» без
    единого слова о том, что вердикт вообще не был получен. Снаружи 100%
    сбоев выглядело неотличимо от «модель говорит true на всё». Теперь
    видно двумя путями: `on_batch_error` — колбэк сразу при сбое пачки
    (для вызывающего кода, который печатает по мере готовности, Г.41);
    заголовок `render_general_requirements_summary_llm_filtered` —
    агрегированный счётчик такого фолбэка, виден всегда, даже если колбэк
    не передан."""
    out: list[RequirementVerdict] = []
    for batch in _chunk_requirements(requirements, batch_size):
        user_text = _render_batch(batch)
        try:
            result = call_llm_json(config, _FILTER_SYSTEM_PROMPT, user_text, timeout=timeout)
        except Exception as exc:  # noqa: BLE001 — сбой одной пачки не должен ронять весь фильтр
            result = None
            if on_batch_error:
                on_batch_error(batch, exc)
        verdicts_by_index: dict[int, dict] = {}
        if result:
            for item in result.get("verdicts", []):
                idx = item.get("index")
                if isinstance(idx, int):
                    verdicts_by_index[idx] = item
        for i, req in enumerate(batch, 1):
            item = verdicts_by_index.get(i)
            if item is None:
                out.append(RequirementVerdict(
                    requirement=req, is_requirement=True,
                    reasoning=_NO_VERDICT_REASON,
                ))
                continue
            out.append(RequirementVerdict(
                requirement=req,
                is_requirement=_parse_verdict_bool(item.get("is_requirement"), True),
                reasoning=str(item.get("reasoning") or ""),
            ))
    return out


def render_general_requirements_summary_llm_filtered(verdicts: list[RequirementVerdict]) -> str:
    """Печатный каталог формы 3 ПОСЛЕ ЛЛМ-фильтра (Г.69) — заменяет собой
    `requirement_registry.render_general_requirements_summary` в выводе,
    когда есть ключ провайдера (без ключа печатается по-старому, сырой
    regex-каталог). Отсеянное как шум показано отдельным видимым списком
    внизу с обоснованием модели, не выброшено молча (Г.10) — инспектор
    может проверить решение."""
    kept = [v for v in verdicts if v.is_requirement]
    dropped = [v for v in verdicts if not v.is_requirement]
    no_verdict = [v for v in verdicts if v.reasoning == _NO_VERDICT_REASON]
    lines = [
        f"=== Требования ПД после ЛЛМ-фильтра (Г.69, форма 3) — "
        f"кандидатов: {len(verdicts)}, оставлено: {len(kept)}, отсеяно как шум: {len(dropped)} ===",
    ]
    if no_verdict:
        # Г.77 — реальная находка: сбой вызова (сеть/ключ/SSL) у ВСЕХ пачек
        # даёт то же "оставлено: N", что и настоящий вердикт модели "это
        # требование" — без этой строки снаружи неотличимо от "модель
        # ничего не отсеивает", хотя на деле она вообще не отвечала.
        lines.append(f"ВНИМАНИЕ: {len(no_verdict)} из {len(verdicts)} кандидатов НЕ получили вердикт "
                     f"ЛЛМ вообще (сбой вызова — сеть, ключ, сертификат) и включены как требования "
                     f"по умолчанию, а не по решению модели — «оставлено» выше по этой причине "
                     f"не значит «модель согласилась».")
    for i, v in enumerate(kept, 1):
        req = v.requirement
        rooms = f" — помещения: {', '.join(req.rooms)}" if req.rooms else ""
        lines.append(f"{i}. стр.{req.page}{rooms}")
        lines.append(f"   «{req.sentence}»")
    if dropped:
        lines.append(f"\n--- отсеяно как шум ({len(dropped)}), для проверки инспектором ---")
        for v in dropped:
            lines.append(f"  стр.{v.requirement.page}: «{v.requirement.sentence}» — {v.reasoning}")
    return "\n".join(lines)
