"""Оси и отметки высот — якорь для листов, где нет экспликации помещений
(Г.5: «план ↔ план (КР, КЖ, КМ) — общий якорь: оси + отметка», а не номер
помещения). Обобщает то, на чём держатся `balance_box.py`/`routing_graph.py`
(оба ключуются `room_key`) на случай пустого реестра помещений — сечения,
узлы, чисто конструктивные листы, схемы систем без привязки к комнате.

## Что реально измерено на живом листе (Г.11 — не гадать)

Замер на `АНО-150321-1-РД-ОВ1 изм. 4_в1 (1)-1-100.pdf`, стр. 17 (план 1
этажа, вентиляция — тот же лист, что и в `routing_graph.py`).

Осевая метка (1-2 кириллические буквы) в текстовом слое ЕСТЬ (в отличие от
подписей веток из `routing_graph.py` — она не в кривых). Но наивный регекс
`^[А-ЯЁ]{1,2}$` сам по себе не отличает настоящую ось от постороннего
короткого текста той же формы: на этом листе нашлось «ВК» (марка
трубопровода, повторяется рядом с каждым его отрезком), «ОВ»/«СС» (то же
самое для других систем) — все той же формы «1-2 кириллические буквы».

Отличать их пришлось не по алфавиту (буквы совпадают), а по ГЕОМЕТРИИ
множества: настоящая осевая линейка — это КОЛОНКА из МНОГИХ РАЗНЫХ букв на
почти одном x (одна метка на каждую ось чертежа), марка трубопровода —
это ОДНА И ТА ЖЕ надпись, повторённая много раз вдоль трубы, тоже на
случайно близких x. Замер: колонка настоящей линейки — 22 записи, x в
пределах 8 pt, все 22 РАЗНЫЕ («АЖ, АД, АА, Д, АГ, АБ, АВ, Ж, Ф, М, В, К,
Н, П, И, Л, Р, Э, Г, Т, Е, С»); колонка марки «ВК» — 8 записей, x в
пределах 3 pt, ВСЕ ОДИНАКОВЫЕ. Разделяет с большим запасом — доля различных
текстов в кластере (`_MIN_DISTINCT_RATIO`).

Кластеризация — не фиксированными корзинами (пробовал: корзина 6 pt
случайно режет настоящую линейку на две соседние корзины из-за джиттера
координат самого PDF, только на корзине 12 pt перестаёт резать эту
конкретную линейку, но это подгонка под один замер, не общее решение) — а
сортировкой по координате с разрывом (`_cluster_1d`): следующая точка
входит в тот же кластер, пока промежуток до предыдущей меньше `_GAP`.
Устойчиво к джиттеру любого размера меньше `_GAP`.

Отметки высот («±0.000», «-0.014», «+3.900») извлекаются проще — тем же
регексом по текстовому слою, без кластеризации: формат с обязательной
точкой и тремя знаками после неё не встретился ни у чего постороннего на
этом же листе."""
from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Sequence

Bbox = tuple[float, float, float, float]

KIND_AXIS = "axis"
KIND_ELEVATION = "elevation"

_AXIS_TOKEN_RE = re.compile(r"^[А-ЯЁ]{1,2}$")
_ELEVATION_RE = re.compile(r"^[+±-]\d+[.,]\d{3}$")

# Разрыв по координате для склейки в один кластер, pt. Замер: настоящая
# линейка укладывается в 8 pt разброса, ближайший другой кластер — на
# сотни pt дальше, порог не критичен в точной величине, лишь бы больше
# джиттера одной линейки и меньше расстояния между разными линейками/маркой.
_GAP = 15.0
# Меньше — недостаточно точек, чтобы отличить линейку от случайного
# совпадения (Г.11 — короткий кластер ничего не доказывает). Замер на
# реальном листе: при пороге 3 кластеризация по y (горизонтальная линейка)
# случайно поймала 3-элементный кластер из одной настоящей осевой метки и
# двух совершенно не связанных марок трубопровода, оказавшихся на близком y
# чисто по совпадению координат на большой странице — 5 отсекает такое
# совпадение с запасом, не трогая настоящую линейку (22 элемента).
_MIN_CLUSTER_SIZE = 5
# Доля РАЗНЫХ текстов в кластере. Замер: настоящая линейка — 22/22 = 1.0,
# повторяющаяся марка трубопровода — 1/8 = 0.125. Порог с большим запасом.
_MIN_DISTINCT_RATIO = 0.6


@dataclass(frozen=True)
class AxisAnchor:
    text: str
    bbox: Bbox
    kind: str = KIND_AXIS

    @property
    def center(self) -> tuple[float, float]:
        return ((self.bbox[0] + self.bbox[2]) / 2, (self.bbox[1] + self.bbox[3]) / 2)


def _cluster_1d(words: Sequence[tuple], coord_index: int, gap: float = _GAP) -> list[list[tuple]]:
    ordered = sorted(words, key=lambda w: w[coord_index])
    clusters: list[list[tuple]] = []
    current: list[tuple] = []
    for w in ordered:
        if current and w[coord_index] - current[-1][coord_index] > gap:
            clusters.append(current)
            current = []
        current.append(w)
    if current:
        clusters.append(current)
    return clusters


def _is_real_ruler(cluster: Sequence[tuple]) -> bool:
    if len(cluster) < _MIN_CLUSTER_SIZE:
        return False
    texts = [w[4] for w in cluster]
    return len(set(texts)) / len(texts) >= _MIN_DISTINCT_RATIO


def extract_axis_anchors(page: "pymupdf.Page") -> list[AxisAnchor]:  # noqa: F821
    """Осевые метки листа: колонки (вертикальная линейка, группировка по x)
    и строки (горизонтальная линейка, группировка по y) короткого текста,
    где кластер несёт в основном РАЗНЫЕ значения — не повторяющуюся марку.

    Пустой список на листе без осевой сетки (стройгенплан со своими
    координатами, текстовый лист) — честный результат, не ошибка."""
    words = page.get_text("words")
    candidates = [w for w in words if _AXIS_TOKEN_RE.match(w[4])]
    if not candidates:
        return []

    seen: set[tuple[float, float, float, float, str]] = set()
    anchors: list[AxisAnchor] = []
    for coord_index in (0, 1):  # 0 = x (вертикальная линейка), 1 = y (горизонтальная)
        for cluster in _cluster_1d(candidates, coord_index):
            if not _is_real_ruler(cluster):
                continue
            for w in cluster:
                key = tuple(w[:5])
                if key in seen:
                    continue
                seen.add(key)
                anchors.append(AxisAnchor(text=w[4], bbox=tuple(w[:4])))
    return anchors


def extract_elevation_anchors(page: "pymupdf.Page") -> list[AxisAnchor]:  # noqa: F821
    """Отметки высот («±0.000», «-0.014», «+3.900») — тоже якорь по Г.5, не
    требует кластеризации: формат сам по себе достаточно специфичен."""
    words = page.get_text("words")
    return [AxisAnchor(text=w[4], bbox=tuple(w[:4]), kind=KIND_ELEVATION)
            for w in words if _ELEVATION_RE.match(w[4])]
