"""ВИД извлечённой строки: требование, исходные данные расчёта, позиция ведомости.

Зачем. Разбор ПД выписывает всё, что описывает объект, — и это правильно для
сводки. Но сверка с рабочей документацией применима не ко всему. На реальном
томе из 531 строки 508 ушли в «требует проверки», и большинство из них
проверить было НЕЧЕМ по природе:

  * названные величины — теплофизические свойства материала, безразмерный
    коэффициент, геометрия помещения — это ИСХОДНЫЕ ДАННЫЕ расчёта, который
    выполнен в самой проектной документации. Рабочая документация их не
    подтверждает и не опровергает: проверять их следует в расчёте;
  * строки ведомости оборудования, повторяющиеся десятками. Их сверяют СО
    СПЕЦИФИКАЦИЕЙ рабочей документации целиком, как два списка, а не
    поштучно через просмотр чертежей.

Смешать это с требованиями значит утопить требования в шуме и потратить
сотни вызовов модели впустую.

Как отличаются — по ФОРМЕ ЗАПИСИ, а не по теме. Правила ниже не знают ни
раздела документации, ни предмета, ни конкретного объекта:

  * есть глагол или норматив («предусмотреть», «не менее», «выполняется»)
    — это ТРЕБОВАНИЕ: сказано, каким должен быть объект;
  * глагола нет, но есть обозначение изделия (буквенно-цифровой код) —
    ПОЗИЦИЯ ВЕДОМОСТИ: назван предмет поставки, а не действие;
  * глагола нет, кода нет, есть величина с единицей измерения — ИСХОДНЫЕ
    ДАННЫЕ: названо значение, и ничего не сказано о том, что с ним делать.

Правила не знают предметной области: они разбирают форму русской фразы и
годятся для любого раздела документации.

Умолчание — ТРЕБОВАНИЕ. Ошибка в сторону «проверить лишнее» стоит вызова
модели, ошибка в другую сторону стоит пропущенного нарушения (Г.10: тихо
выбрасывать нельзя, и число строк каждого вида показывается в отчёте).
"""
from __future__ import annotations

import re

KIND_REQUIREMENT = "требование"
KIND_INPUT_DATA = "исходные данные"
KIND_SPEC_ITEM = "позиция ведомости"
KINDS = (KIND_REQUIREMENT, KIND_INPUT_DATA, KIND_SPEC_ITEM)

# Нормативная граница значения: «не менее 2,2 м» — это уже не измеренная
# величина, а предъявленное к объекту условие.
_BOUND_RE = re.compile(
    r"\bне\s+(?:менее|более|ниже|выше|допус\w*|реже|чаще)\b|"
    r"\bдолж\w+\b|\bследует\b|\bнеобходимо\b|\bобязан\w*\b|\bпредел\w*\s+огнестойкости\b",
    re.IGNORECASE)

# Глагольные формы русского языка: личные глаголы, инфинитивы, краткие
# причастия («предусмотрена», «приняты», «оснащены»). Признак того, что в
# строке сказано ДЕЙСТВИЕ или СОСТОЯНИЕ объекта, а не названа величина.
# Окончания «-та/-ты/-то» сюда НЕ входят намеренно: под них попадают
# существительные («теплота», «высота», «работа»), и строка с величиной
# становилась бы требованием. Проверено на реальных строках разбора.
_VERB_RE = re.compile(
    r"\b\w+(?:ться|тся|ется|ются|ается|аются|ится|ятся)\b|"          # возвратные
    r"\b\w{3,}(?:ать|ять|ить|еть|уть|ыть|очь)\b|"                     # инфинитивы
    r"\b\w{4,}(?:ена|ены|ено|ана|аны|ано|ята|яты|ято)\b",            # краткие причастия
    re.IGNORECASE)

# Единица измерения после числа. Список форм, а не «любое слово»: иначе
# «250 кг верхней одежды» и «250 помещений» стали бы неразличимы.
_VALUE_RE = re.compile(
    r"\d[\d\s.,–-]*\s*"
    r"(?:мм|см|м²|м2|м³|м3|м/с|м³/ч|м3/ч|кг/м²|кг/м2|кг|г|т|"
    r"°\s*[CС]|К\b|Па|кПа|гПа|МПа|мм\s*рт|Вт|кВт|МВт|кВт·ч|"
    r"МДж/кг|МДж|кДж/кг|кДж|Дж|В\b|А\b|Гц|л/ч|л|%|об/мин|сут\w*|"
    r"шт\.?|компл\.?|м\b)",
    re.IGNORECASE)

# Ссылка на норматив изделием не является: номер свода правил или стандарта
# — это документ, а не марка. Принимать его за обозначение значит объявить
# ведомостью любое требование, где назван норматив.
_NORM_REF_RE = re.compile(r"\b(?:ГОСТ|СП|СНиП|СанПиН|ТУ|ISO|EN|DIN)\b[\s№]*[\d.\-/]+",
                          re.IGNORECASE)

# Обозначение изделия — латиница рядом с цифрами. Две формы, потому что в
# документах встречаются обе: слитная («KF-IW-22B-V», «V1.40-4.0x30.R») и
# раздельная, где марка и типоразмер разнесены пробелом («WNK 160/1»,
# «KDV DU 400-80A»). Одним выражением это не описать без ложных
# срабатываний, поэтому проверка идёт по токенам.
_LATIN_TOKEN_RE = re.compile(r"[A-Za-z][A-Za-z0-9\-/.х×]*")
_FOLLOWED_BY_NUMBER_RE = re.compile(r"\s*[-–]?\s*\d")


def _has_designation(text: str) -> bool:
    for match in _LATIN_TOKEN_RE.finditer(text):
        token = match.group(0)
        if any(c.isdigit() for c in token) and any(c.isalpha() for c in token):
            return True
        if len(token) >= 2 and _FOLLOWED_BY_NUMBER_RE.match(text[match.end():]):
            return True
    return False


# «Название — число» без действия и без единицы измерения: безразмерный
# коэффициент, количество, номер. Это тоже названное значение, а не
# требование к объекту.
# Дефис без пробелов сюда не входит: «14918-80» — это диапазон или
# номер внутри обозначения, а не подпись к значению.
_LABELLED_VALUE_RE = re.compile(r"(?:[—–:]|\s-\s)\s*\d")


def _without_norm_refs(sentence: str) -> str:
    """Строка без ссылок на нормативы: номер стандарта — не марка изделия."""
    return _NORM_REF_RE.sub(" ", sentence)


def classify(sentence: str) -> str:
    """Вид строки. Умолчание — требование: тихо не проверить хуже, чем
    проверить лишнее (Г.10)."""
    text = (sentence or "").strip()
    if not text:
        return KIND_REQUIREMENT
    if _BOUND_RE.search(text) or _VERB_RE.search(text):
        return KIND_REQUIREMENT
    stripped = _without_norm_refs(text)
    if _has_designation(stripped):
        return KIND_SPEC_ITEM
    if _VALUE_RE.search(stripped) or _LABELLED_VALUE_RE.search(stripped):
        return KIND_INPUT_DATA
    return KIND_REQUIREMENT


def split_by_kind(requirements: list) -> dict[str, list]:
    """Разложить список требований по видам, сохранив порядок внутри вида."""
    out: dict[str, list] = {kind: [] for kind in KINDS}
    for item in requirements:
        out[classify(getattr(item, "sentence", "") or "")].append(item)
    return out
